#!/usr/bin/env python3
"""посчитать_маршруты.py — канонический счёт маршрутов живого приложения.

## ЗАЧЕМ СКРИПТ, А НЕ ЧИСЛО В ПАСПОРТЕ (27.10.2026)

В документах одновременно жили 189, 200, 201 и 253 «маршрута», и все четыре
были по-своему правдивы: их получали разными способами — grep по декораторам
(253: считает и мёртвые дубликаты, и роутеры, которые никто не подключает),
подсчёт путей в OpenAPI (241 путь / 244 операции: не видит маршруты с
`include_in_schema=False`), `len(app.routes)` (20: современная FastAPI
оставляет включённые роутеры обёртками `_IncludedRouter`, а не раскрытым
списком).

Ни одно из этих чисел не отвечает на вопрос «сколько дверей у сайта». Отвечает
обход дерева маршрутов живого приложения — он же и вскрывает расхождения:
дубль `/api/ak/passport/extract` был виден только как разница между
«зарегистрировано» и «уникальных пар (путь, метод)».

И у обхода дерева есть своя граница, из-за которой первое издание скрипта
дало 249 вместо 250: считать надо ту точку входа, которая реально поднята.
Боевой сайт запускается как `api.railway_entry:app` (замерено 28.08.2026,
`KNOWN_ISSUES.md` M6), а она дообъявляет `GET /healthz` — путь проверки
здоровья Railway. Импорт `api.main` его не видит. Скрипт поэтому печатает
два числа: состав `api.main` и итог на боевой точке входа.

## ЧТО ИЗМЕНИЛОСЬ 28.10.2026: ОБХОД ДЕРЕВА СТАЛ ОДИН НА ДВУХ

Скрипт остался КАНОНИЧЕСКОЙ КОМАНДОЙ — паспорта цитируют его вывод, и число
маршрутов в репозитории по-прежнему одно (дефект L5). Изменилось место, где
лежит реализация обхода: `обойти`, `посчитать`, `маршруты_точки_входа` и
`собрать_числа` живут в `api/meta_counts.py`, а этот скрипт их импортирует.

Причина — новый маршрут `GET /api/meta/counts`, который отдаёт то же самое
число живой первой странице сайта: до него лендинг скачивал весь
`/openapi.json` (249 905 байт без сжатия, 45 450 байт gzip, 0.49 с — замер на
живом сайте 28.10.2026) ради одной цифры.
Рантайму нужен тот же обход, что и скрипту, и вариантов было два:

* две реализации (скрипт + api/) — разошлись бы при первом же обновлении
  FastAPI, и сайт показывал бы одно число, а паспорт другое;
* рантайм импортирует dev-скрипт по пути к файлу — боевой сайт начал бы
  зависеть от присутствия папки `scripts/` в контейнере.

Поэтому реализация переехала в `api/`, а команда и её вывод остались прежними.
Расхождение между скриптом и эндпоинтом этот же скрипт и ловит: последняя
строка вывода печатает, что реально отдаёт `GET /api/meta/counts`, а при
несовпадении скрипт возвращает код 2.

Запуск:
    PYTHONUTF8=1 python scripts/посчитать_маршруты.py
    PYTHONUTF8=1 python scripts/посчитать_маршруты.py --список   # все пути
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from api.meta_counts import (  # noqa: E402
    маршруты_точки_входа,
    обойти,
    посчитать,
    собрать_числа,
    текущее,
)

# Реэкспорт: тесты и любой другой код, который читает канонический обход
# «из скрипта», обязаны находить его здесь, как и раньше.
__all__ = ["обойти", "посчитать", "маршруты_точки_входа", "собрать_числа",
           "текущее", "main"]


def main() -> int:
    from api.main import app

    сводка = посчитать(app)
    spec = app.openapi()
    операций = sum(len(v) for v in spec["paths"].values())
    точка_входа = маршруты_точки_входа()
    боевой = сводка["http_всего"] + len(точка_входа)

    print(f"HTTP-маршрутов зарегистрировано   : {сводка['http_всего']}")
    print(f"  из них своих (без docs/openapi)  : {сводка['http_своих']}")
    print(f"уникальных пар (путь, метод)       : {сводка['пар_путь_метод']}")
    print(f"уникальных путей                   : {сводка['уникальных_путей']}")
    print(f"WebSocket                          : {сводка['websocket']}")
    print(f"служебных маршрутов документации   : {сводка['служебных_документации']}")
    print(f"скрыто из OpenAPI                  : {сводка['вне_openapi']}")
    print(f"OpenAPI: путей / операций          : {len(spec['paths'])} / {операций}")
    print(f"\nдообъявлено в api/railway_entry.py : {len(точка_входа)}")
    for путь, метод in точка_входа:
        print(f"   {метод:7} {путь}")
    print(f"ИТОГО на боевой точке входа        : {боевой} HTTP "
          f"+ {сводка['websocket']} WS")

    # Что отдаёт сайт. `текущее()` — снимок, зафиксированный при импорте
    # `api.main` (конец модуля), то есть ровно то, что увидит лендинг.
    отдаёт = текущее() or собрать_числа(app)
    print(f"GET /api/meta/counts отдаёт        : {отдаёт['http']} HTTP "
          f"+ {отдаёт['ws']} WS")
    расходится = (отдаёт["http"] != боевой
                  or отдаёт["ws"] != сводка["websocket"])
    if расходится:
        print("\nРАСХОЖДЕНИЕ: эндпоинт отдаёт не то число, которое посчитал "
              "скрипт. Это дефект L5 (два числа маршрутов в одном репозитории).")

    if сводка["дубликаты"]:
        print(f"\nДУБЛИКАТЫ (путь, метод) — {len(сводка['дубликаты'])}:")
        for k in сводка["дубликаты"]:
            print("   ", k)
    else:
        print("\nдубликатов (путь, метод) нет")
    if "--список" in sys.argv:
        print(f"\nвсе {len(сводка['список'])} пар (путь, метод) в api.main:")
        for p, m in сводка["список"]:
            print(f"   {m:7} {p}")
    return 2 if расходится else (1 if сводка["дубликаты"] else 0)


if __name__ == "__main__":
    raise SystemExit(main())
