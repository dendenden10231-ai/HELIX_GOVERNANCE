class СкорерЯдра:
    """score(text, test_id) -> статус ядра HELIX для текста против статьи позиции."""

    def __init__(self, пары: list[dict]) -> None:
        self.пары = пары

    def score(self, text: str, test_id) -> str:
        from helix_pipeline.engine.привязка_чисел import привязать
        источник = self.пары[int(test_id)]["статья"]
        return привязать(text or "", источник)["status"]


class СкорерБатареи:
    """score(text, test_id) -> вердикт батареи AK-MASTER по кодам FAIL/WARN."""

    def score(self, text: str, test_id) -> str:
        from api.service import ak_service
        отчёт = ak_service.audit_text_raw(text or "")
        коды = sorted(
            п.get("code", "?") for п in отчёт.get("auto_checks", [])
            if п.get("status") in ("FAIL", "WARN")
        )
        return f"F{отчёт.get('fail_count')}|W{len(отчёт.get('warnings') or [])}|{','.join(коды)}"


class СкорерСверки:
    """score(text, test_id) -> результат дословной сверки разметки с досье.

    Разметка позиции постоянна между руками: акторы и цитаты взяты из её
    собственного досье, источник один. Движется только текст досье.
    """

    def __init__(self) -> None:
        self.разметки = []
        for досье in PROBE_MR:
            цитаты = [с for с in _цитаты(досье)]
            self.разметки.append({
                "actors": [
                    {"name": "сторона A", "kind": "company", "quote": цитаты[0] if цитаты else "",
                     "loses": "долю рынка"},
                    {"name": "сторона B", "kind": "regulator", "quote": цитаты[1] if len(цитаты) > 1 else "",
                     "loses": "спор"},
                ],
                "deeds": [{"date": "2026-03-01", "kind": "filing", "url": "https://example.org/1"}],
            })

    def score(self, text: str, test_id) -> str:
        from mr_helix.engine.market_новости import проверить_разметку
        итог = проверить_разметку(
            self.разметки[int(test_id)], text or "",
            [{"url": "https://example.org/1"}],
        )
        return json.dumps(итог, ensure_ascii=False, sort_keys=True, default=str)


def _цитаты(текст: str) -> list[str]:
    out, открыта = [], False
    буфер = ""
    for знак in текст:
        if знак == "«":
            открыта = True
            буфер = ""
        elif знак == "»" and открыта:
            открыта = False
            out.append(буфер)
        elif открыта:
            буфер += знак
    return out


def выбрать_пары() -> list[dict]:
    с_числами, без_чисел = [], []
    for строка in НАБОР.read_text(encoding="utf-8").splitlines():
        пара = json.loads(строка)
        корзина = с_числами if пара["helix_статус"] != "NO_NUMBERS" else без_чисел
        if len(корзина) < ПОЛОВИНА:
            корзина.append(пара)
        if len(с_числами) == ПОЛОВИНА and len(без_чисел) == ПОЛОВИНА:
            break
    return с_числами + без_чисел


def прогнать(имя: str, скорер, позиции: list[str], ответы: list[str]) -> None:
    print(f"\n########## прибор: {имя} ##########")
    print(f"позиций: {len(позиции)}")
    verdict, rows = зонд.run(
        [{"id": str(k)} for k in range(len(позиции))],
        скорер, ответы, random.Random(ЗЕРНО), do_refusal=True,
    )
    инертные = [t for t, ref, row, moved in rows if ref is not None and not moved]
    print(f"инертные позиции: {len(инертные)} из {len(позиции)}: {инертные}")
    print(f"verdict: {verdict}")


def main() -> None:
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("helix", "all"):
        пары = выбрать_пары()
        прогнать("helix: привязать() — ядро HELIX", СкорерЯдра(пары),
                 [п["пересказ"] for п in пары], [п["пересказ"] for п in пары])
    if what in ("ak", "all"):
        прогнать("ak: батарея автопроверок AK-MASTER", СкорерБатареи(),
                 PROBE_AK, PROBE_AK)
    if what in ("mr", "all"):
        прогнать("mr: дословная сверка разметки Mr. Helix", СкорерСверки(),
                 PROBE_MR, PROBE_MR)


if __name__ == "__main__":
    main()
